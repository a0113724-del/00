"""Generate tokens.css + tailwind-theme.css from tokens.json and check WCAG contrast of every pair.
Standard library only. Exit code 1 if any pair fails.
Usage: python3 build_tokens.py
"""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
T = json.load(open(os.path.join(HERE, 'tokens.json'), encoding='utf-8'))


def lum(hexc):
    h = hexc.lstrip('#')
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    f = lambda c: c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    return 0.2126 * f(r) + 0.7152 * f(g) + 0.0722 * f(b)


def ratio(a, b):
    la, lb = sorted([lum(a), lum(b)], reverse=True)
    return (la + 0.05) / (lb + 0.05)


# ---------- contrast report
lines = ['# Contrast report (WCAG 2.x)', '', '| theme | fg | bg | ratio | min | result |', '|---|---|---|---|---|---|']
fails = 0
for theme, pal in T['color'].items():
    for p in T['pairs']:
        r = ratio(pal[p['fg']], pal[p['bg']])
        ok = r >= p['min']
        fails += not ok
        lines.append(f"| {theme} | {p['fg']} | {p['bg']} | {r:.2f} | {p['min']} | {'pass' if ok else '**FAIL**'} |")
lines += ['', f'Failures: {fails}']
open(os.path.join(HERE, 'contrast-report.md'), 'w', encoding='utf-8').write('\n'.join(lines) + '\n')

# ---------- tokens.css (custom properties; dark default, light via [data-theme=light])
def block(sel, pal):
    out = [f'{sel} {{']
    out += [f'  --sb-color-{k}: {v};' for k, v in pal.items()]
    return out

css = ['/* generated by build_tokens.py — do not edit by hand */']
css += block(':root, [data-theme="dark"]', T['color']['dark'])
f = T['font']
css += [f"  --sb-font-sans: {f['family']['sans']};", f"  --sb-font-mono: {f['family']['mono']};"]
for k, v in f['size'].items(): css.append(f'  --sb-text-{k}: {v};')
for k, v in f['line'].items(): css.append(f'  --sb-leading-{k}: {v};')
for k, v in T['space'].items(): css.append(f'  --sb-space-{k}: {v};')
for k, v in T['radius'].items(): css.append(f'  --sb-radius-{k}: {v};')
for k, v in T['shadow'].items(): css.append(f'  --sb-shadow-{k}: {v};')
for k, v in T['motion'].items(): css.append(f'  --sb-motion-{k}: {v};')
css += ['  color-scheme: dark;', '}', '']
css += block('[data-theme="light"]', T['color']['light']) + ['  color-scheme: light;', '}']
open(os.path.join(HERE, 'tokens.css'), 'w', encoding='utf-8').write('\n'.join(css) + '\n')

# ---------- Tailwind v4 theme mapping: utilities like bg-surface, text-muted read the CSS variables
tw = ['/* generated by build_tokens.py — Tailwind v4 theme mapping */', '@theme inline {']
for k in T['color']['dark']:
    name = 'muted' if k == 'text-muted' else k
    tw.append(f'  --color-{name}: var(--sb-color-{k});')
tw += ['  --font-sans: var(--sb-font-sans);', '  --font-mono: var(--sb-font-mono);']
for k in f['size']: tw += [f'  --text-{k}: var(--sb-text-{k});', f'  --text-{k}--line-height: var(--sb-leading-{k});']
for k in T['radius']: tw.append(f'  --radius-{k}: var(--sb-radius-{k});')
for k in T['shadow']: tw.append(f'  --shadow-{k}: var(--sb-shadow-{k});')
tw.append('}')
open(os.path.join(HERE, 'tailwind-theme.css'), 'w', encoding='utf-8').write('\n'.join(tw) + '\n')

# copy into the web app
WEB = os.path.join(HERE, '..', '..', 'web', 'src', 'styles')
if os.path.isdir(os.path.dirname(WEB)):
    os.makedirs(WEB, exist_ok=True)
    for fn in ('tokens.css', 'tailwind-theme.css'):
        open(os.path.join(WEB, fn), 'w', encoding='utf-8').write(open(os.path.join(HERE, fn), encoding='utf-8').read())

print(f'pairs checked: {len(T["pairs"]) * len(T["color"])}, failures: {fails}')
if fails:
    print('\n'.join(l for l in lines if 'FAIL' in l))
    sys.exit(1)
